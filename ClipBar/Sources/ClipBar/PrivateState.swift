import Cocoa
import Darwin

// The daemon and UI can share a profile; destructive maintenance requires both
// to release the shared runtime lock. A separate daemon lock prevents duplicates.
enum PrivateState {
    static let directory: URL = {
        if let path = ProcessInfo.processInfo.environment["CLIPBAR_CONFIG_DIR"] {
            return URL(fileURLWithPath: NSString(string: path).expandingTildeInPath).standardizedFileURL
        }
        return URL(fileURLWithPath: NSHomeDirectory() + "/.config/clipd")
    }()
    static var clipboard: NSPasteboard {
        if let name = ProcessInfo.processInfo.environment["CLIPBAR_PASTEBOARD_NAME"] {
            return NSPasteboard(name: NSPasteboard.Name(name))
        }
        return .general
    }
    static let excludedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping", "Pasteboard generator type", "com.agilebits.onepassword"
    ]
    static func excluded(_ pasteboard: NSPasteboard) -> Bool {
        !(pasteboard.types ?? []).allSatisfy { !excludedTypes.contains($0.rawValue) }
    }
    static func path(_ name: String) -> String { directory.appendingPathComponent(name).path }

    static func lock() -> Int32? {
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true,
                                                attributes: [.posixPermissions: 0o700])
        let parent = open(directory.path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW)
        guard parent >= 0 else { return nil }
        defer { close(parent) }
        var info = stat()
        guard fstat(parent, &info) == 0, info.st_uid == getuid(), fchmod(parent, 0o700) == 0 else { return nil }
        let fd = openat(parent, "runtime.lock", O_RDWR | O_CREAT | O_NOFOLLOW | O_NONBLOCK, 0o600)
        guard fd >= 0 else { return nil }
        guard fstat(fd, &info) == 0, (info.st_mode & S_IFMT) == S_IFREG,
              info.st_uid == getuid(), info.st_nlink == 1, fchmod(fd, 0o600) == 0,
              flock(fd, LOCK_SH | LOCK_NB) == 0 else { close(fd); return nil }
        return fd
    }

    static func safeDatabase() -> Bool {
        let fd = open(path("history.db"), O_RDWR | O_NOFOLLOW | O_NONBLOCK)
        guard fd >= 0 else { return false }
        defer { close(fd) }
        var info = stat()
        return fstat(fd, &info) == 0 && (info.st_mode & S_IFMT) == S_IFREG &&
            info.st_uid == getuid() && info.st_nlink == 1 && fchmod(fd, 0o600) == 0
    }
    static func setFlag(_ name: String, enabled: Bool) {
        let url = directory.appendingPathComponent(name)
        if enabled {
            // Atomic replacement avoids following an existing flag symlink.
            try? Data().write(to: url, options: [.atomic])
            chmod(url.path, 0o600)
        } else {
            try? FileManager.default.removeItem(at: url)
        }
    }
}
